"""Regenerate frontend/src/lib/demo/sample.ts, the recorded run shown on the sample page.

Everything comes from a real run's own output: the sync result (`python -m forkward sync ... >
result.json`) and its run log under runs/<run_id>/. Hunks, candidates, votes, confidences, gate
reasons and the timeline are copied, never typed in, and the models are named from the attempts log.

    uv run python -m e2e.sample_fixture runs/demo-rehearsal.json runs/sync-20261025T032435-6db174
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "frontend/src/lib/demo/sample.ts"
# Which job stage each step of a sync belongs to, as the web app shows stages.
STAGES = {
    "fetch_upstream": "fetch",
    "merge": "merge",
    "detect_conflicts": "merge",
    "apply": "review",
}


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def build(result: dict, run: Path) -> dict:
    events = read_jsonl(run / "events.jsonl")
    attempts = read_jsonl(run / "attempts.jsonl")
    models = Counter(f"{a['provider']}:{a['model']}" for a in attempts if a.get("model"))
    checks = {e["hunk"]: e for e in events if e.get("agent") == "gate" and e["kind"] == "decision"}
    hunks = []
    for i, h in enumerate(result["hunks"]):
        auto = h["gate"] == "auto_apply"
        chosen = next(c for c in h["detail"]["candidates"] if c["chosen"])
        hunks.append(
            {
                "id": f"sample-{i + 1}",
                "file": h["file"],
                "idx": i,
                "hunk_ref": h["hunk_id"],
                "decision": "auto" if auto else "review",
                "confidence": round(h["confidence"], 3),
                "source": "+".join(chosen["sources"]),
                "reason": h["reason"],
                "applied": auto,
                "review": None,
                "resolution": h["resolution"],
                "final_resolution": None,
                "review_commit": None,
                "detail": {
                    **h["detail"],
                    "passed_checks": bool(checks.get(h["hunk_id"], {}).get("accepted")),
                },
            }
        )
    timeline = []
    for e in events:
        if e.get("agent") == "sync" and e["kind"] == "step":
            timeline.append((e["ts"], STAGES.get(e["task"], "resolve"), "stage", e["message"]))
        elif e.get("agent") == "controller" and e["kind"] == "start":
            n = len(hunks)
            timeline.append((e["ts"], "resolve", "stage", f"Resolving {n} conflict hunks"))
        elif e.get("agent") == "controller" and e["kind"] == "done":
            msg = f"Resolved {len(hunks)} hunks in {e['latency_s']:.1f} s"
            timeline.append((e["ts"], "resolve", "info", msg))
        elif e.get("agent") == "sync" and e["kind"] == "alert" and e.get("level") == "needs_review":
            timeline.append((e["ts"], "review", "warning", e["message"]))
    first, last = events[0]["ts"], events[-1]["ts"]
    auto = sum(h["applied"] for h in hunks)
    return {
        "id": "sample",
        "repo": result["repo"],
        "kind": "preview",
        "status": "succeeded",
        "stage": "done",
        "progress": {"done": len(hunks), "total": len(hunks)},
        "pr_url": result.get("pr_url"),
        "summary": {
            "hunks": len(hunks),
            "auto_applied": auto,
            "needs_review": len(hunks) - auto,
            "branch": result.get("branch"),
            "clean_merge": result["clean_merge"],
            "upstream_sha": result.get("upstream_sha"),
            "strategy": result.get("strategy"),
            "models": dict(models),
            "run_id": run.name,
        },
        "error": None,
        "created_at": first,
        "updated_at": last,
        "upstream_ref": result["upstream"],
        "base": "main",
        "branch": result.get("branch"),
        "review_requested": 0,
        "review_applied": 0,
        "hunks": hunks,
        "events": [
            {"id": n + 1, "ts": ts, "stage": stage, "kind": kind, "message": msg, "data": {}}
            for n, (ts, stage, kind, msg) in enumerate(timeline)
        ],
    }


def main(argv: list[str]) -> int:
    result, run = json.loads(Path(argv[0]).read_text()), Path(argv[1])
    job = build(result, run)
    models = ", ".join(job["summary"]["models"])
    OUT.write_text(
        "/**\n"
        f" * A recorded run, shown on the sample page with the same view as a real job: {job['repo']}\n"
        f" * merging {job['upstream_ref']}, run {run.name}, with {models}. Every hunk, vote,\n"
        " * confidence, gate reason and timeline entry is copied from that run's own output.\n"
        " *\n"
        " * Generated by e2e/sample_fixture.py. Do not edit by hand.\n"
        " */\n"
        'import type { JobDetail } from "@/lib/jobs";\n\n'
        f"export const SAMPLE_JOB: JobDetail = {json.dumps(job, indent=1)};\n"
    )
    print(f"wrote {OUT} ({len(job['hunks'])} hunks, {models})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
